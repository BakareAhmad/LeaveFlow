                            AddDetailRow(table, 2, "Task Operations", "Active Department Tasks",
                                d.OpenTasks.ToString(), "Assigned, in progress, or submitted for review", false);
                            AddDetailRow(table, 3, "Task Operations", "Overdue Tasks",
                                d.OverdueTasks.ToString(), "Active tasks past due date needing attention",
                                d.OverdueTasks > 0);
                            AddDetailRow(table, 4, "Expense Claims", "Pending Expense Claims",
                                d.PendingExpenses.ToString(), "Claims awaiting Administrator approval",
                                d.PendingExpenses > 0);
                            AddDetailRow(table, 5, "Expense Claims", "Approved Reimbursements",
                                d.ApprovedExpenseTotal.ToString("C"),
                                "Cumulative approved claims paid or queued", false);
                            AddDetailRow(table, 6, "Performance Appraisals", "Open Appraisal Cycles",
                                d.OpenReviewCycles.ToString(), "Review cycles open for submission", false);
                            AddDetailRow(table, 7, "Performance Appraisals", "Pending Employee Reviews",
                                d.PendingPerformanceReviews.ToString(),
                                "Reviews awaiting manager comment or submission",
                                d.PendingPerformanceReviews > 0);
                        });

                        // Governance note
                        col.Item().PaddingTop(14).Text("Operations Note")
                            .FontSize(12).Bold().FontColor("#18181B");

                        col.Item().PaddingTop(6).Border(1).BorderColor("#E4E4E7")
                            .Background("#FAFAFA").Padding(8)
                            .Column(govCol =>
                            {
                                govCol.Item().Text("• Review pending leave requests before the start date to avoid scheduling conflicts.")
                                    .FontSize(8f).FontColor("#52525B");
                                govCol.Item().PaddingTop(2)
                                    .Text("• Follow up on overdue tasks to keep work on track.")
                                    .FontSize(8f).FontColor("#52525B");
                                govCol.Item().PaddingTop(2)
                                    .Text("• Manager expense claims are reviewed by the Administrator; receipts should be attached.")
                                    .FontSize(8f).FontColor("#52525B");
                                govCol.Item().PaddingTop(2)
                                    .Text("• Department managers are expected to submit the department review report after completing staff appraisals.")
                                    .FontSize(8f).FontColor("#52525B");
                            });
                    });

                    // Footer
                    page.Footer().Column(col =>
                    {
                        col.Item().LineHorizontal(0.5f).LineColor("#E4E4E7");
                        col.Item().PaddingTop(5).Row(row =>
                        {
                            row.RelativeItem().Text("LeaveFlow Employee Operations Portal")
                                .FontSize(7.5f).FontColor("#A1A1AA");
