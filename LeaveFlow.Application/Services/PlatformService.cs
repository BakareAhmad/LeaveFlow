    public class OperationsReportService(IOperationsReportRepository repository,
            IOrganisationAccessService accessService,
            IDepartmentRepository departmentRepository,
            IUserRepository userRepository) : IOperationsReportService
    {
        public async Task<BaseResponse<OperationsReportDto>> GetAsync(
            Guid userId,
            OperationsReportFilterRequest filter)
        {
            var context = await accessService.GetContextAsync(userId);
            if (!context.Status || context.Data == null)
            {
                return new BaseResponse<OperationsReportDto> { Message = context.Message };
            }

            if (filter.EndDate.HasValue
                && filter.StartDate.HasValue
                && filter.EndDate < filter.StartDate)
            {
                return new BaseResponse<OperationsReportDto>
                {
                    Message = "End date cannot be earlier than start date."
                };
            }

            Guid? departmentId = null;
            if (!context.Data.IsSystemAdmin)
            {
                departmentId = context.Data.DepartmentId;
            }

            var report = await repository.GetAsync(
                departmentId,
                filter.StartDate,
                filter.EndDate);

            var user = await userRepository.GetByIdAsync(userId);
            if (user != null)
            {
                report.GeneratedBy = $"{user.Employee.FirstName} {user.Employee.LastName} ({user.Email})";
            }
            else
            {
                report.GeneratedBy = "System User";
            }

            report.GeneratedAt = DateTime.UtcNow;

            if (context.Data.IsSystemAdmin)
            {
                report.ScopeName = "All Departments";
            }
            else
            {
                var dept = await departmentRepository.GetByIdAsync(context.Data.DepartmentId);
                report.ScopeName = dept != null ? $"{dept.Name} Department" : "Department";
            }

            return new BaseResponse<OperationsReportDto>
            {
                Status = true,
                Data = report
            };
        }

        public async Task<BaseResponse<string>> ExportCsvAsync(
            Guid userId,
            OperationsReportFilterRequest filter)
        {
            var result = await GetAsync(userId, filter);
            if (!result.Status || result.Data == null)
            {
                return new BaseResponse<string> { Message = result.Message };
            }

            var d = result.Data;
            var csv = new StringBuilder();

            csv.AppendLine("LeaveFlow Operations Summary Report");
            csv.AppendLine($"Scope,\"{d.ScopeName}\"");
            csv.AppendLine($"Generated By,\"{d.GeneratedBy}\"");
            csv.AppendLine($"Generated At,\"{d.GeneratedAt:yyyy-MM-dd HH:mm:ss} UTC\"");

            var startLabel = d.StartDate.HasValue ? d.StartDate.Value.ToString("yyyy-MM-dd") : "All Time";
            var endLabel = d.EndDate.HasValue ? d.EndDate.Value.ToString("yyyy-MM-dd") : "All Time";
            csv.AppendLine($"Date Filter Range,\"{startLabel} to {endLabel}\"");
            csv.AppendLine();
            csv.AppendLine("Module,Operational Metric,Value,Context");
            csv.AppendLine($"Human Resources,Total Active Employees,{d.Employees},Staff members within scope");
            csv.AppendLine($"Leave Management,Pending Leave Requests,{d.PendingLeave},Applications awaiting review");
            csv.AppendLine($"Task Operations,Open Department Tasks,{d.OpenTasks},Tasks in progress or awaiting acceptance");
            csv.AppendLine($"Task Operations,Overdue Department Tasks,{d.OverdueTasks},Tasks past scheduled due date");
            csv.AppendLine($"Expense Claims,Pending Reimbursement Claims,{d.PendingExpenses},Claims submitted for Admin review");
            csv.AppendLine($"Expense Claims,Approved Reimbursement Total,{d.ApprovedExpenseTotal:0.00},Cumulative approved expense claims");
            csv.AppendLine($"Performance Appraisals,Open Appraisal Cycles,{d.OpenReviewCycles},Appraisal cycles currently open");
            csv.AppendLine($"Performance Appraisals,Pending Employee Reviews,{d.PendingPerformanceReviews},Reviews pending completion");

            return new BaseResponse<string>
            {
                Status = true,
                Data = csv.ToString()
            };
        }

