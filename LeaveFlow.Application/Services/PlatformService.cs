            QuestPDF.Settings.License = LicenseType.Community;

            var dateRangeText = BuildDateRangeText(d);

            var document = Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(32);
                    page.DefaultTextStyle(style => style.FontSize(10)
                        .FontFamily("Helvetica", "Arial", "sans-serif")
                        .FontColor("#18181B"));

                    // Header
                    page.Header().Column(col =>
                    {
                        col.Item().Row(row =>
                        {
                            row.RelativeItem().Column(brandCol =>
                            {
                                brandCol.Item().Text("LEAVEFLOW")
                                    .FontSize(20).Bold().FontColor("#EF001F");
                                brandCol.Item().Text("Employee Operations Portal")
                                    .FontSize(11).SemiBold().FontColor("#52525B");
                                brandCol.Item().PaddingTop(2).Text("Operations Summary Report")
                                    .FontSize(13).Bold().FontColor("#18181B");
                            });

                            row.ConstantItem(230)
                                .Border(1).BorderColor("#E4E4E7")
                                .Background("#FAFAFA").Padding(8)
                                .Column(metaCol =>
                                {
                                    metaCol.Item().Text($"Scope: {d.ScopeName}")
                                        .FontSize(8.5f).Bold().FontColor("#18181B");
                                    metaCol.Item().Text($"Period: {dateRangeText}")
                                        .FontSize(8f).FontColor("#52525B");
                                    metaCol.Item().Text($"Generated: {d.GeneratedAt:dd MMM yyyy HH:mm} UTC")
                                        .FontSize(8f).FontColor("#52525B");
                                    metaCol.Item().Text($"Generated By: {d.GeneratedBy}")
                                        .FontSize(7.5f).FontColor("#71717A");
                                });
                        });

                        col.Item().PaddingTop(8)
                            .LineHorizontal(1.5f).LineColor("#EF001F");
                    });

                    // Content
                    page.Content().PaddingTop(12).Column(col =>
                    {
                        // Key indicators
                        col.Item().Text("Key Operational Indicators")
                            .FontSize(12).Bold().FontColor("#18181B");

                        col.Item().PaddingTop(6).Table(kpiTable =>
                        {
                            kpiTable.ColumnsDefinition(cols =>
                            {
                                cols.RelativeColumn();
                                cols.RelativeColumn();
                                cols.RelativeColumn();
                                cols.RelativeColumn();
                            });

                            AddKpiCell(kpiTable, "ACTIVE STAFF",
                                d.Employees.ToString(), "Total staff in scope", "#18181B");
                            AddKpiCell(kpiTable, "PENDING LEAVE",
                                d.PendingLeave.ToString(), "Awaiting review",
                                d.PendingLeave > 0 ? "#C2410C" : "#15803D");
                            AddKpiCell(kpiTable, "OPEN TASKS",
                                d.OpenTasks.ToString(), "In progress or review", "#18181B");
                            AddKpiCell(kpiTable, "OVERDUE TASKS",
                                d.OverdueTasks.ToString(), "Past scheduled due date",
                                d.OverdueTasks > 0 ? "#DC2626" : "#15803D");
                            AddKpiCell(kpiTable, "PENDING EXPENSES",
                                d.PendingExpenses.ToString(), "Awaiting Admin review",
                                d.PendingExpenses > 0 ? "#C2410C" : "#15803D");
                            AddKpiCell(kpiTable, "APPROVED EXPENSES",
                                d.ApprovedExpenseTotal.ToString("C"), "Approved claims total", "#15803D");
                            AddKpiCell(kpiTable, "ACTIVE CYCLES",
                                d.OpenReviewCycles.ToString(), "Open appraisal cycles", "#18181B");
                            AddKpiCell(kpiTable, "PENDING APPRAISALS",
                                d.PendingPerformanceReviews.ToString(), "In review / unsigned",
                                d.PendingPerformanceReviews > 0 ? "#C2410C" : "#15803D");
                        });

                        // Detailed breakdown
                        col.Item().PaddingTop(14).Text("Detailed Metrics Breakdown")
                            .FontSize(12).Bold().FontColor("#18181B");

                        col.Item().PaddingTop(6).Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.RelativeColumn(2.5f);
                                columns.RelativeColumn(3.5f);
                                columns.RelativeColumn(2.0f);
                                columns.RelativeColumn(4.0f);
                            });

                            // Header row
                            table.Cell().Background("#F4F4F5")
                                .BorderBottom(1).BorderColor("#D4D4D8")
                                .Padding(6).Text("Module")
                                .FontSize(8.5f).Bold().FontColor("#3F3F46");
                            table.Cell().Background("#F4F4F5")
                                .BorderBottom(1).BorderColor("#D4D4D8")
                                .Padding(6).Text("Operational Metric")
                                .FontSize(8.5f).Bold().FontColor("#3F3F46");
                            table.Cell().Background("#F4F4F5")
                                .BorderBottom(1).BorderColor("#D4D4D8")
                                .Padding(6).Text("Value / Total")
                                .FontSize(8.5f).Bold().FontColor("#3F3F46");
                            table.Cell().Background("#F4F4F5")
