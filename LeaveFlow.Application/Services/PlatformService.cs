                            {
                                text.Span("Page ").FontSize(7.5f).FontColor("#A1A1AA");
                                text.CurrentPageNumber().FontSize(7.5f).FontColor("#A1A1AA");
                                text.Span(" of ").FontSize(7.5f).FontColor("#A1A1AA");
                                text.TotalPages().FontSize(7.5f).FontColor("#A1A1AA");
                            });
                        });
                    });
                });
            });

            var pdfBytes = document.GeneratePdf();
            return new BaseResponse<byte[]>
            {
                Status = true,
                Data = pdfBytes,
                Message = "PDF report generated successfully."
            };
        }

        private static string BuildDateRangeText(OperationsReportDto d)
        {
            if (d.StartDate.HasValue && d.EndDate.HasValue)
            {
                return $"{d.StartDate.Value:dd MMM yyyy} - {d.EndDate.Value:dd MMM yyyy}";
            }

            if (d.StartDate.HasValue)
            {
                return $"From {d.StartDate.Value:dd MMM yyyy}";
            }

            if (d.EndDate.HasValue)
            {
                return $"Until {d.EndDate.Value:dd MMM yyyy}";
            }

            return "All Time";
        }

        private static void AddKpiCell(
            TableDescriptor kpiTable,
            string title,
            string value,
            string subtitle,
            string valueColor)
        {
            kpiTable.Cell().Padding(3)
                .Border(1).BorderColor("#E4E4E7")
                .Background("#FFFFFF").Padding(7)
                .Column(card =>
                {
                    card.Item().Text(title).FontSize(7.5f).SemiBold().FontColor("#71717A");
                    card.Item().PaddingTop(2).Text(value).FontSize(14).Bold().FontColor(valueColor);
                    card.Item().PaddingTop(2).Text(subtitle).FontSize(7f).FontColor("#A1A1AA");
                });
        }

        private static void AddDetailRow(
            TableDescriptor table,
            int index,
            string module,
            string metric,
            string value,
            string context,
            bool isAlert)
        {
            var bg = index % 2 == 0 ? "#FFFFFF" : "#FAFAFA";
            var valueColor = isAlert ? "#DC2626" : "#18181B";

            table.Cell().Background(bg)
                .BorderBottom(1).BorderColor("#E4E4E7")
                .Padding(6).Text(module)
                .FontSize(8.5f).SemiBold().FontColor("#18181B");
            table.Cell().Background(bg)
                .BorderBottom(1).BorderColor("#E4E4E7")
                .Padding(6).Text(metric)
                .FontSize(8.5f).FontColor("#3F3F46");
            table.Cell().Background(bg)
                .BorderBottom(1).BorderColor("#E4E4E7")
                .Padding(6).Text(value)
                .FontSize(9f).Bold().FontColor(valueColor);
            table.Cell().Background(bg)
                .BorderBottom(1).BorderColor("#E4E4E7")
                .Padding(6).Text(context)
                .FontSize(8f).FontColor("#71717A");
        }
    }
